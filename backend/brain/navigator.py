def _recommend(service, state, language, found, intro_other=False):
    de = language == "de"
    topic = found["topic"]["label_de" if de else "label_en"]
    why = f"Diese Stelle hilft beim Thema {topic}." if de else f"This service helps with: {topic}."
    phone = _first_phone(service)
    card = _service_card(service, why)
    if de:
        lead = f"Eine andere Möglichkeit ist {service['name']}." if intro_other else f"{service['name']} kann Ihnen helfen."
        contact = (f" Sie erreichen die Stelle unter {phone}." if phone else
                   (f" Die Adresse ist {card['address']}. Eine Telefonnummer habe ich dafür leider nicht."
                    if card["address"] else " Eine Telefonnummer habe ich dafür leider nicht."))
    else:
        lead = f"Another option is {service['name']}." if intro_other else f"{service['name']} can help you."
        contact = (f" You can call them on {phone}." if phone else
                   (f" The address is {card['address']}. I'm sorry, I don't have a phone number for it."
                    if card["address"] else " I'm sorry, I don't have a phone number for it."))
    reply = lead + contact
    _remember(state, service)
    return {"reply_text": reply, "needs_more_info": False, "service": card}


def _remember(state, service):
    state["service_id"] = service["id"]
    state["category"] = service.get("category") or state["category"]
    if service["id"] not in state["shown"]:
        state["shown"].append(service["id"])


def _rules(found, language, state, current, alternative, user_text):
    de = language == "de"
    if alternative and current:
        on_topic = current["id"] in set(_get_retriever().links.get(state.get("topic_id"), []))
        if on_topic:     # e.g. another Sozialstation: same kind of service, next nearest
            other = _pick(found["all_hits"], state, same_category=current.get("category"), skip_shown=True)
        else:            # after a general office: the nearest specialised service on the topic
            pool = [h for h in _ordered(found["all_hits"], state)
                    if h["id"] not in state["shown"] and h.get("category") not in FIRST_CONTACT]
            other = pool[0] if pool else None
        if other:
            return _recommend(other, state, language, found, intro_other=True)
        place = _region_name(state["region"])
        return {"reply_text": (f"In meinen Daten gibt es{' in ' + place if place else ''} leider keine weitere Stelle "
                               "für dieses Thema. Sie können auch die kostenlose, anonyme Online-Beratung der Caritas nutzen."
                               if de else
                               f"I'm sorry, my data has no other service for this{' in ' + place if place else ''}. "
                               "You can also use the free, anonymous online counselling of Caritas."),
                "needs_more_info": True, "service": None}
    if current and _words(normalize(user_text)) <= 3 and not region_of_text(user_text):
        return {"reply_text": (f"Haben Sie noch eine Frage zu {current['name']}, oder geht es um ein anderes Thema?"
                               if de else
                               f"Do you have another question about {current['name']}, or is it about something else?"),
                "needs_more_info": True, "service": None}
    first = _pick(found["hits"], state)
    if not state["region"] and not state["town"] and (found["needs_location"] or (first and first["region"] is not None)):
        state["location_asks"] += 1
        state["awaiting_location"] = state["location_asks"] <= 2
        if state["location_asks"] == 1:
            return {"reply_text": ("Ich helfe Ihnen gern. In welchem Ort oder Landkreis wohnen Sie? "
                                   "Dann finde ich die Beratungsstelle in Ihrer Nähe." if de else
                                   "I'm happy to help. Which town or district do you live in? "
                                   "Then I can find the service near you."),
                    "needs_more_info": True, "service": None}
        if state["location_asks"] == 2:
            return {"reply_text": ("Entschuldigung, den Ort habe ich nicht richtig verstanden. Sagen Sie mir bitte "
                                   "Ihre Postleitzahl oder die nächste größere Stadt." if de else
                                   "Sorry, I didn't quite catch the place. Please tell me your postcode "
                                   "or the nearest bigger town."),
                    "needs_more_info": True, "service": None}
        # third time: stop asking; offer a region-wide or nationwide service instead
        wide = [h for h in _rank_local(found["hits"], state) if h.get("region") is None and h.get("kind") == "hotline"]
        if wide:
            out = _recommend(wide[0], state, language, found)
            out["reply_text"] = ("Ich empfehle Ihnen erst einmal eine Stelle, die überall erreichbar ist. "
                                 if de else "For now, here is a service you can reach from anywhere. ") + out["reply_text"]
            return out
        return {"reply_text": ("Sie können sich auch an die kostenlose, anonyme Online-Beratung der Caritas wenden. "
                               "Dort hilft man Ihnen, die richtige Stelle zu finden." if de else
                               "You can also use the free, anonymous online counselling of Caritas. "
                               "They will help you find the right place."),
                "needs_more_info": True, "service": None}
    best = _pick(found["all_hits"], state)
    if best is not None and current is not None and best["id"] == current["id"]:
        phone = _first_phone(best)
        return {"reply_text": (f"{best['name']} bleibt die passende Stelle für Sie."
                               + (f" Sie erreichen sie unter {phone}." if phone else "") if de else
                               f"{best['name']} is still the best fit for you."
                               + (f" You can call them on {phone}." if phone else "")),
                "needs_more_info": False, "service": None}
    if best is None:
        return {"reply_text": ("Erzählen Sie mir bitte etwas mehr, wobei Sie Hilfe brauchen."
                               if de else "Please tell me a bit more about what you need help with."),
                "needs_more_info": True, "service": None}
    return _recommend(best, state, language, found)


