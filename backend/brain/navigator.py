def navigate(session_id, history, user_text, language):
    language = language if language in ("de", "en") else "de"
    de = language == "de"
    history = history or []
    with _sessions_lock:
        state = _sessions.setdefault(session_id, _new_state())
        if not history:                       # a new conversation reusing an id
            state.update(_new_state())

    # 1. crisis: fixed, safe reply
    crisis = detect_crisis(user_text)
    if crisis:
        sid, reply_de, reply_en, why_de, why_en = _CRISIS[crisis]
        s = _service_by_id(sid) or (_find_category("Telefonseelsorge") if crisis == "suicide" else None)
        return {"reply_text": reply_de if de else reply_en, "needs_more_info": False,
                "service": _service_card(s, why_de if de else why_en) if s else None}

    # 2. greetings, thanks, okay, goodbye
    small = _smalltalk(user_text, language)
    if small:
        return {"reply_text": small, "needs_more_info": True, "service": None}

    alternative = bool(_ALTERNATIVE.search(normalize(user_text)))
    current = _service_by_id(state["service_id"])

    # 3. a follow-up question about the service already recommended: answer about THAT service only
    if current and not alternative and _is_followup(user_text, state):
        log.info("navigate: follow-up question about %s", current["id"])
        return _answer_followup(history, user_text, language, current)

    # 4. search the database, guided by the conversation memory
    topic_before = state["topic_text"]
    query = _plan_search(user_text, state, alternative)
    new_problem = state["topic_text"] is not topic_before and state["topic_text"] == user_text
    wide = alternative or state["region"] or state["town"]
    found = _search(query, state, k=200 if wide else 20, new_problem=new_problem)
    found["all_hits"] = found["hits"]
    found["hits"] = _ordered(found["all_hits"], state)[:CANDIDATES]
    local_door = _first_contact_nearby(found["all_hits"], state)
    if local_door and local_door["id"] not in {h["id"] for h in found["hits"]}:
        found["hits"].append(local_door)
    log.info("navigate: query=%r town=%s region=%s alternative=%s top=%s", query, state["town"], state["region"],
             alternative, [h["id"] for h in found["hits"][:3]])

    # 4. LLM leads the conversation; it may only recommend from the search results
    if USE_LLM:
        try:
            out = _call_llm(_build_messages(history, user_text, language, found, state, current, alternative))
            reply = _clean(out.get("reply"))
            action = _clean(out.get("action")).lower()
            if not reply:
                raise ValueError("empty reply")
            if action == "recommend":
                allowed = {h["id"]: h for h in found["hits"]}
                if current:
                    allowed.setdefault(current["id"], current)
                chosen = allowed.get(_clean(out.get("service_id")))
                if chosen is None:
                    raise ValueError(f"recommended an unknown service: {out.get('service_id')!r}")
                _remember(state, chosen)
                return {"reply_text": reply, "needs_more_info": False,
                        "service": _service_card(chosen, out.get("why") or "")}
            if action == "ask" and _LOCATION_CUE.search(normalize(reply)):
                state["awaiting_location"] = True
                state["location_asks"] += 1
            return {"reply_text": reply, "needs_more_info": action != "answer", "service": None}
        except (urllib.error.URLError, TimeoutError, ConnectionError) as e:
            log.warning("LLM not reachable at %s (%s) - using rule-based replies", LLM_BASE_URL, e)
        except Exception:
            log.exception("LLM reply unusable - using rule-based replies")

    return _rules(found, language, state, current, alternative, user_text)
