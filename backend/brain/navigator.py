def _service_line(s: dict) -> str:
    fields = [("id", s["id"]), ("name", s.get("name")), ("category", s.get("category")),
              ("town", s.get("city")), ("region", s.get("region") or "region-wide / nationwide"),
              ("address", s.get("address")), ("coverage", s.get("coverage")), ("phone", s.get("phone")),
              ("hours", s.get("hours")), ("contact", s.get("contact_mode")), ("access", s.get("access_rule")),
              ("cost", s.get("cost_note")), ("note", s.get("confidence_note")), ("keywords", s.get("keywords_en"))]
    return " | ".join(f"{k}: {_clean(v)}" for k, v in fields if _clean(v))


