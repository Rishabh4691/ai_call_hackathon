_towns = None


def _town_index():
    """normalized town name -> {"name", "region"} for every town in the database."""
    global _towns
    if _towns is None:
        from .geocode import load_geo, region_of_county

        geo = load_geo()
        _towns = {}
        for sv in _get_retriever().services:
            city = _clean(sv.get("city"))
            if not city or "/" in city or "," in city or "nationwide" in city.lower():
                continue
            key = normalize(city)
            if len(key) >= 4 and key not in _towns:
                plz = _clean(sv.get("postcode"))[:5]
                g = geo.get(key)
                _towns[key] = {"name": city, "postcode": int(plz) if plz.isdigit() else None,
                               "region": (region_of_county(g["county"]) if g else None) or sv.get("region"),
                               "coords": (g["lat"], g["lon"]) if g else None}
    return _towns


def _town_of_text(text: str):
    """The longest known town name mentioned in the text, or None."""
    t = normalize(text)
    best = None
    for key, info in _town_index().items():
        if re.search(r"(?<![a-z])" + re.escape(key) + r"(?![a-z])", t) and (best is None or len(key) > len(best[0])):
            best = (key, info)
    return best[1] if best else None


_LOCATION_CUE = re.compile(r"\b(wohne|wohnen|wohnt|lebe|leben|live|living|komme aus|ort|stadt|dorf|landkreis|"
                           r"postleitzahl|postcode|zip code|town|village|district)\b")
_GENERIC_PLACE_WORDS = {"bad", "main", "an", "der", "am", "saale", "neustadt"}
_POSTCODE = re.compile(r"(?<!\d)(6[3-9]\d{3}|9[0-7]\d{3})(?!\d)")


def _place_by_postcode(text: str):
    """A Lower Franconian postcode in the text -> the town with the nearest postcode."""
    m = _POSTCODE.search(text)
    if not m:
        return None
    plz = int(m.group(1))
    towns = [t for t in _town_index().values() if t.get("postcode")]
    return min(towns, key=lambda t: abs(t["postcode"] - plz)) if towns else None


def _fuzzy_place(text: str):
    """Tolerate speech-recognition errors in place names ("mein Spessort" -> Main-Spessart).
    Returns ("region", key) or ("town", info) or None."""
    words = normalize(text).replace("-", " ").split()
    grams = [" ".join(words[i:i + n]) for n in (3, 2, 1) for i in range(len(words) - n + 1)]
    targets = []
    for key, aliases in REGIONS.items():
        for alias in aliases:
            a = normalize(alias).replace("-", " ")
            targets.append((a, ("region", key)))
            targets += [(w, ("region", key)) for w in a.split() if len(w) >= 6 and w not in _GENERIC_PLACE_WORDS]
    targets += [(k.replace("-", " "), ("town", info)) for k, info in _town_index().items() if len(k) >= 5]
    best, best_score = None, 0.0
    for g in grams:
        if len(g) < 5:
            continue
        for name, place in targets:
            need = 0.84 if " " not in name else 0.8
            score = SequenceMatcher(None, g, name).ratio()
            if score >= need and score > best_score:
                best, best_score = place, score
    return best


def warm_up() -> None:
    """Load the database and the embedding model now, so the first conversation is not slow."""
    _get_retriever()
    _town_index()


def _service_by_id(sid):
    if not sid:
        return None
    for s in _get_retriever().services:
        if s["id"] == sid:
            return s
    return None


def _find_category(word: str):
    """First service whose category contains the word (e.g. the Telefonseelsorge office)."""
    for sv in _get_retriever().services:
        if word.lower() in (sv.get("category") or "").lower():
            return sv
    return None


def _clean(value) -> str:
    return re.sub(r"\s+", " ", str(value or "")).strip()


def _service_card(s: dict, why: str) -> dict:
    """Map a database row to the contract's service object."""
    place = " ".join(p for p in (_clean(s.get("postcode")), _clean(s.get("city"))) if p)
    address = ", ".join(p for p in (_clean(s.get("address")), place) if p)
    return {
        "id": s["id"],
        "name": _clean(s.get("name")),
        "why": _clean(why),
        "address": address,
        "phone": _clean(s.get("phone")),
        "email": _clean(s.get("email")),
        "website": _clean(s.get("website")),
        "opening_hours": _clean(s.get("hours")),
        "languages": [],          # not in the source data; never guessed
    }


def _first_phone(s: dict) -> str:
    return _clean(re.split(r"[;,]", s.get("phone") or "")[0])


def _region_name(region_key):
    return (region_key or "").title()


