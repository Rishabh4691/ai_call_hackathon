def _is_followup(user_text: str, state: dict) -> bool:
    """A question about the current service, not a new problem."""
    t = normalize(user_text)
    if _FOLLOWUP_CUE.search(t):
        return True
    if not _QUESTION.search(t):
        return False
    # a question without a back-reference: follow-up unless it clearly names a different topic
    topic = _get_retriever().search(user_text, [], k=1)["topic"]["id"]
    return topic == state.get("topic_id") or _words(t) <= 6


def _answer_followup(history, user_text, language, service):
    de = language == "de"
    if USE_LLM:
        try:
            lang_name = "German" if de else "English"
            msgs = [{"role": "system", "content": _FOLLOWUP_SYSTEM.format(lang_name=lang_name)}]
            for turn in history[-6:]:
                msgs.append({"role": "assistant" if turn.get("role") == "assistant" else "user",
                             "content": _clean(turn.get("text"))})
            msgs.append({"role": "user", "content": f"SERVICE: {_service_line(service)}\n\nTHE PERSON ASKS: {user_text}"})
            reply = _clean(_call_llm(msgs).get("reply"))
            if reply:
                return {"reply_text": reply, "needs_more_info": False, "service": None}
        except (urllib.error.URLError, TimeoutError, ConnectionError) as e:
            log.warning("LLM not reachable at %s (%s) - using rule-based replies", LLM_BASE_URL, e)
        except Exception:
            log.exception("LLM follow-up unusable - using rule-based reply")
    return {"reply_text": _rule_followup(user_text, service, de), "needs_more_info": False, "service": None}


def _rule_followup(user_text: str, s: dict, de: bool) -> str:
    """Answer a follow-up from the service's own fields; say so honestly when the data has no answer."""
    t = normalize(user_text)
    card = _service_card(s, "")
    name = card["name"]
    if re.search(r"\b(where|address|how do i get|wo ist|adresse|wie komme ich|wo)\b", t) and card["address"]:
        return f"Die Adresse von {name} ist {card['address']}." if de else f"The address of {name} is {card['address']}."
    if re.search(r"\b(phone|call|number|telefon|anrufen|nummer)\b", t):
        if card["phone"]:
            return f"Sie erreichen {name} unter {card['phone']}." if de else f"You can call {name} on {card['phone']}."
        return (f"Eine Telefonnummer von {name} habe ich leider nicht. Die Adresse ist {card['address']}."
                if de else f"I'm sorry, I don't have a phone number for {name}. The address is {card['address']}.")
    if re.search(r"\b(open|opening|hours|when|geoffnet|offnungszeiten|wann)\b", t) and card["opening_hours"]:
        return (f"Laut meinen Daten: {card['opening_hours']}" if de else f"According to my data: {card['opening_hours']}")
    return (f"Dazu habe ich leider keine genauen Informationen. Am besten fragen Sie direkt bei {name} nach."
            + (f" Die Adresse ist {card['address']}." if card["address"] else "")
            if de else
            f"I'm sorry, I don't have exact information about that. It's best to ask {name} directly."
            + (f" The address is {card['address']}." if card["address"] else ""))


def _build_messages(history, user_text, language, found, state, current, alternative):
    lang_name = "German" if language == "de" else "English"
    topic = found["topic"]
    shown = [s for s in (_service_by_id(i) for i in state["shown"]) if s]
    context = [
        f"needs_location: {str(found['needs_location']).lower()}",
        f"town known: {state['town'] or 'not yet'}; district: {_region_name(state['region']) or 'not yet'}",
        f"the person asks for another option: {'yes' if alternative else 'no'}",
        f"times you already asked for the town: {state['location_asks']}",
        f"best matching topic: {topic['label_en']} / {topic['label_de']}",
        f"useful questions for this topic: {_clean(topic.get('clarification'))}",
        f"handling note: {_clean(topic.get('handling_note'))}",
        "ALREADY SUGGESTED: " + ("; ".join(f"{s['id']} {s['name']}" for s in shown) if shown else "none"),
        "CURRENT SERVICE (the last one suggested):",
        f"- {_service_line(current)}" if current else "- none",
        "CANDIDATES:",
        *[f"- {_service_line(h)}" for h in found["hits"]],
    ]
    msgs = [{"role": "system", "content": SYSTEM_PROMPT.format(lang_name=lang_name)}]
    for turn in history[-10:]:
        role = "assistant" if turn.get("role") == "assistant" else "user"
        msgs.append({"role": role, "content": _clean(turn.get("text"))})
    msgs.append({"role": "user", "content": "DATA FOR THIS TURN\n" + "\n".join(context)
                 + f"\n\nTHE PERSON SAYS: {user_text}"})
    return msgs


def _call_llm(messages) -> dict:
    body = {"model": LLM_MODEL, "messages": messages, "temperature": 0.2, "max_tokens": 350,
            "response_format": {"type": "json_object"}}
    req = urllib.request.Request(f"{LLM_BASE_URL}/chat/completions", data=json.dumps(body).encode(),
                                 headers={"Content-Type": "application/json",
                                          "Authorization": f"Bearer {LLM_API_KEY}"}, method="POST")
    with urllib.request.urlopen(req, timeout=LLM_TIMEOUT) as resp:
        content = json.loads(resp.read().decode())["choices"][0]["message"]["content"]
    match = re.search(r"\{.*\}", content, re.DOTALL)
    if not match:
        raise ValueError(f"no JSON in LLM output: {content[:200]!r}")
    return json.loads(match.group(0))


