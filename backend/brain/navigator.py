def _words(t: str) -> int:
    return len(re.findall(r"\w+", t))


def _smalltalk(text: str, language: str):
    """Greeting, thanks, okay, goodbye. Questions and real requests are never treated as small talk."""
    t = normalize(text)
    de = language == "de"
    n = _words(t)
    if _GREETING.match(t):
        return ("Hallo! Ich bin der Caritas-Wegweiser. Erzählen Sie mir einfach, wobei Sie Hilfe brauchen."
                if de else "Hello! I am the Caritas Wegweiser. Just tell me what you need help with.")
    if _BYE.search(t) and n <= 10:
        return ("Alles Gute für Sie. Auf Wiedersehen!" if de else "All the best to you. Goodbye!")
    if _QUESTION.search(t):
        return None
    if (_THANKS.search(t) and n <= 8) or _ACK.match(t):
        return ("Gern geschehen. Kann ich Ihnen noch bei etwas anderem helfen?"
                if de else "You're welcome. Is there anything else I can help you with?")
    return None


# ---------------------------------------------------------------- search with memory
def _plan_search(user_text: str, state: dict, alternative: bool):
    """Search text = the person's PROBLEM only. Town and district are remembered in the state and decide the
    ORDER of the results (nearest first), so a town name never pulls in services just because of their name."""
    t = normalize(user_text)
    region_now = region_of_text(user_text)
    town = _town_of_text(user_text)
    if not region_now and not town:
        town = _place_by_postcode(user_text)
        if not town:
            fuzzy = _fuzzy_place(user_text)
            if fuzzy and fuzzy[0] == "region":
                region_now = fuzzy[1]
            elif fuzzy:
                town = fuzzy[1]
            if fuzzy:
                log.info("place understood despite spelling: %r -> %s", user_text, fuzzy)
    if town:
        state["town"] = town["name"]
        state["postcode"] = town["postcode"]
        state["coords"] = town.get("coords")
        region_now = town["region"] or region_now
    if region_now:
        state["region"] = region_now

    answering_location = state["awaiting_location"] and _words(t) <= 8
    state["awaiting_location"] = False
    if alternative and (state["topic_text"] or state["category"]):
        return f"{state['topic_text'] or ''} {state['category'] or ''}".strip()
    if state["topic_text"] and (answering_location or ((region_now or town or _LOCATION_CUE.search(t)) and _words(t) <= 6)):
        return state["topic_text"]           # an answer about the location: the earlier problem stays the topic
    if _words(t) >= 3:
        state["topic_text"] = user_text      # a description of the problem
    return state["topic_text"] or user_text


def _search(query: str, state: dict, k: int, new_problem: bool):
    found = _get_retriever().search(query, [], k=k)
    if new_problem or not state["topic_id"]:
        state["topic_id"] = found["topic"]["id"]
    if state["region"] and not found["region"]:
        found["region"] = state["region"]
        found["needs_location"] = False
    return found


def _on_topic(hits, state):
    """Hits that belong to the remembered topic (so a town match alone never wins)."""
    tid = state.get("topic_id")
    direct_top = ("direct#1 ", "direct#2 ", "direct#3 ")
    linked = [h for h in hits if (tid and any(r.startswith(f"topic {tid}#") for r in h.get("reasons", [])))
              or any(r.startswith(direct_top) for r in h.get("reasons", []))]
    return linked or hits


def _km(a, b):
    lat1, lon1, lat2, lon2 = map(math.radians, (*a, *b))
    x = math.sin((lat2 - lat1) / 2) ** 2 + math.cos(lat1) * math.cos(lat2) * math.sin((lon2 - lon1) / 2) ** 2
    return 6371 * 2 * math.asin(math.sqrt(x))


def _locality(h, state):
    """0 = in the person's town, 1 = same district, 2 = region-wide / nationwide, 3 = elsewhere."""
    city = normalize(h.get("city") or "")
    if state["town"] and city == normalize(state["town"]):
        return 0
    if state["region"] and h.get("region") == state["region"]:
        return 1
    if h.get("region") is None:
        return 2
    return 3 if state["region"] else 2


def _distance(h, state):
    here = state.get("coords")
    there = (_town_index().get(normalize(h.get("city") or "")) or {}).get("coords")
    if here and there:
        return _km(here, there)
    plz = _clean(h.get("postcode"))[:5]
    return abs(int(plz) - state["postcode"]) if state.get("postcode") and plz.isdigit() else 0


def _linked(h, state):
    tid = state.get("topic_id")
    return bool(tid) and any(r.startswith(f"topic {tid}#") for r in h.get("reasons", []))


def _ordered(hits, state):
    """All results in the order we would recommend them:
       1. on the person's topic AND in their town / district (nearest first)
       2. the local general counselling office (first door for any problem)
       3. on the topic, further away (nearest first)
       4. other strong text matches"""
    near = lambda h: _locality(h, state) <= 1
    key = lambda h: (_locality(h, state), 0 if _clean(h.get("phone")) else 1, _distance(h, state), -h["score"])
    linked = [h for h in hits if _linked(h, state)]
    tiers = [
        sorted([h for h in linked if near(h)], key=key),
        sorted([h for h in hits if h.get("category") in FIRST_CONTACT and near(h)],
               key=lambda h: (_locality(h, state), 0 if "caritasverband" in normalize(h.get("name") or "") else 1,
                              _distance(h, state), -h["score"])),
        sorted([h for h in linked if not near(h)], key=key),
        [h for h in hits if any(r.startswith(("direct#1 ", "direct#2 ", "direct#3 ")) for r in h.get("reasons", []))],
    ]
    out, seen = [], set()
    for tier in tiers:
        for h in tier:
            if h["id"] not in seen:
                seen.add(h["id"])
                out.append(h)
    return out or list(hits)


def _rank_local(hits, state):
    return _ordered(hits, state)


FIRST_CONTACT = ("General social counselling", "Local Caritas office (first contact)", "General / reception",
                 "Caritas community service")


def _first_contact_nearby(hits, state):
    """The general counselling office in the person's town or district: the first door for any problem."""
    if not (state["town"] or state["region"]):
        return None
    near = [h for h in hits if h.get("category") in FIRST_CONTACT and _locality(h, state) <= 1
            and h["id"] not in state["shown"]]
    return sorted(near, key=lambda h: (_locality(h, state), 0 if _clean(h.get("phone")) else 1))[0] if near else None


def _pick(hits, state, same_category=None, skip_shown=False):
    """First hit in recommendation order; optionally of one category and not suggested before."""
    pool = [h for h in _ordered(hits, state) if not (skip_shown and h["id"] in state["shown"])]
    if same_category:
        pool = [h for h in pool if h["category"] == same_category]
    return pool[0] if pool else None


